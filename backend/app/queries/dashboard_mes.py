SQL_META_MES = """
    SELECT COALESCE(ROUND(META, 2), 0) AS META
    FROM METAFUNCIONARIO
    WHERE CODIGOFUNCIONARIO = ?
"""

SQL_PERCENTUAL_META_MES = """
    SELECT
        COALESCE(
            ROUND(
                (
                    SUM(A.TOTALLIQUIDO)
                    / NULLIF(MAX(B.META), 0)
                ) * 100,
                2
            ),
            0
        ) AS PERCENTUAL
    FROM MOVIMENTO A
    INNER JOIN METAFUNCIONARIO B
        ON A.CODIGOFUNCIONARIO = B.CODIGOFUNCIONARIO
    WHERE A.CODIGOOPERACAO = '12102'
      AND A.CODIGOFUNCIONARIO = ?
      AND A.DATA >= DATEFROMPARTS(YEAR(GETDATE()), MONTH(GETDATE()), 1)
      AND A.DATA < DATEADD(DAY, 1, CAST(GETDATE() AS DATE))
"""

