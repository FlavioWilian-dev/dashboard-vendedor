SQL_PEDIDOS_FEITOS_MES = """
    SELECT COALESCE(SUM(TOTALLIQUIDO), 0) AS VALOR
    FROM MOVIMENTO
    WHERE CODIGOOPERACAO = '12102'
      AND CODIGOFUNCIONARIO = ?
      AND DATA >= DATEFROMPARTS(YEAR(GETDATE()), MONTH(GETDATE()), 1)
      AND DATA < DATEADD(DAY, 1, CAST(GETDATE() AS DATE))
"""

